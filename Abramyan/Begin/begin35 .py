V = float(input("Введите скорость в стояч воде: "))
U = float(input("Введите скорость течения реки: "))
T = float(input("Введите время вниз по теч: "))
T2 = float(input("Введите время вверз по теч: "))
if U < V:
    print('Значение введено неверно')
else: 
    S = V * T + V * T2
    print(round(S , 2))
